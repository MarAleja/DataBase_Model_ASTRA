"""check_quality.py - aplica la regla de calidad a cada grabacion y escribe QUALITY-REPORT.md.

Escrito por el equipo con ayuda de Claude (IA). Lo explica cualquier miembro.

Uso:  python code/check_quality.py            (datos reales)
      python code/check_quality.py --simulado (ensayo con data/simulado/)

La regla esta escrita ANTES de ver cualquier score (PROTOCOL.md, paso 9):
rechazar una grabacion si una muestra toca el limite del ADC (0 o 16383), si
falta mas del 1 % de las muestras, si su largo se aleja mas de 2 % del plan, si
la Fs medida se aleja mas de 2 % de 1000 Hz, o si quien opera la rechazo al grabar.
data/raw/ no se toca: solo se actualiza data/metadata.csv y el reporte.
"""
import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from emg_cuello import calidad                                            # noqa: E402
from emg_cuello.config import RAIZ, cargar_config, carpeta                # noqa: E402
from emg_cuello.datos import (escribir_metadata, leer_metadata,           # noqa: E402
                              leer_registro, ruta_de_fila)
from emg_cuello.filtros import adc_a_voltios                              # noqa: E402
from emg_cuello.procesar import rms_por_fase, senal_sinarm                # noqa: E402

REGLA = ("Rule, written before any score: reject a recording if a sample sits at the limit "
         "of the converter (0 or 16383 with 14 bits), if more than 1 % of its samples are "
         "missing (counter of the Arduino), if its length is more than 2 % away from the "
         "plan (15 s x 1000 Hz = 15000 samples), if the measured sampling rate is more than "
         "2 % away from 1000 Hz, or if the operator rejected it while recording (the person "
         "moved at the wrong time, an electrode came loose).")


def revisar_fila(fila, cfg, ruta):
    """Recalcula la calidad desde el archivo. Regresa (fila actualizada, rms, cero_v)."""
    df = leer_registro(ruta)
    plan = int(round(sum(float(fila[c]) for c in ("rest_s", "warning_s", "move_s",
                                                  "between_s")) * cfg["fs_hz"]))
    fs_real = float(fila["fs_measured_hz"]) if fila["fs_measured_hz"] not in ("", "nan") \
        else float("nan")
    rev = calidad.revisar(df["sample"], df["emg_adc"], plan, cfg["adc_bits"], fs_real,
                          cfg["fs_hz"])
    rech, razones = calidad.decidir(rev, cfg["quality"], fila["operator_ok"] != "no",
                                    fila["operator_note"])
    fila = dict(fila)                           # metadata se guarda como texto
    fila["n_samples"] = str(rev["n_samples"])
    fila["missing_pct"] = f"{rev['missing_pct']:.3f}"
    fila["clipped_samples"] = str(rev["clipped_samples"])
    fila["trials_rejected"] = str(int(rech))
    fila["notes"] = "; ".join(razones)
    reposo = df["phase"] == "rest"
    cero_v = float(np.mean(adc_a_voltios(df.loc[reposo, "emg_adc"], cfg["vref_v"],
                                         cfg["adc_bits"])))
    rms = rms_por_fase(senal_sinarm(df, cfg), df["phase"].to_numpy(), cfg["fs_hz"],
                       cfg["windows"]["skip_after_cue_s"])
    return fila, rms, cero_v


def atipicos(tabla, columna, k=3.0):
    """Grabaciones a mas de k MAD de la mediana (en log), dentro de una columna."""
    x = np.log(tabla[columna].astype(float))
    med = np.median(x)
    mad = 1.4826 * np.median(np.abs(x - med))
    if mad == 0:
        return []
    return list(tabla.loc[np.abs(x - med) > k * mad, "file_name"])


def escribir_reporte(meta, resumen, ruta_reporte):
    lineas = ["# Quality report", "",
              "Generated by `code/check_quality.py`. Do not edit by hand: run the script again.",
              "", REGLA, "",
              "| File | Session | Set | Trials | Rejected | Reason |",
              "|---|---|---|---|---|---|"]
    for _, f in meta.iterrows():
        razon = f["notes"] if str(f["trials_rejected"]) == "1" else "kept"
        lineas.append(f"| {f['file_name']} | {f['session']} | {f['set']} | {f['trials']} | "
                      f"{f['trials_rejected']} | {razon} |")
    rech = meta["trials_rejected"].astype(str) == "1"
    notas = meta.loc[rech, "notes"]
    lineas += ["", "**Totals.** "
               f"{len(meta)} recordings recorded, one trial each. {int(rech.sum())} rejected: "
               f"{int(notas.str.contains('limit of the converter').sum())} for samples at the "
               f"limit of the converter (an artifact), "
               f"{int(notas.str.contains('missing').sum())} for missing samples (a gap), "
               f"{int(notas.str.contains('length').sum())} for the wrong length, "
               f"{int(notas.str.contains('Fs').sum())} for the sampling rate, "
               f"{int(notas.str.contains('operator').sum())} by the operator. "
               f"{int((~rech).sum())} kept: "
               f"{int(((~rech) & (meta['set'] == 'train')).sum())} for training, "
               f"{int(((~rech) & (meta['set'] == 'test')).sum())} for the test.", ""]
    if len(resumen):
        lineas += ["**Noise.** SinArm RMS of the kept training recordings, without the first "
                   "second of each phase. Median per session. Test sessions are not opened.", "",
                   "| Session | Recordings | Zero level (V) | Rest RMS (mV) | Up RMS (mV) | Up / rest |",
                   "|---|---|---|---|---|---|"]
        for s, g in resumen.groupby("session"):
            r, m = g["rest_rms_mv"].median(), g["move_rms_mv"].median()
            lineas.append(f"| {s} | {len(g)} | {g['zero_level_v'].median():.3f} | {r:.2f} | "
                          f"{m:.2f} | {m / r:.1f} |")
        candidatos = atipicos(resumen, "rest_rms_mv") + atipicos(resumen, "move_rms_mv")
        lineas += ["", "**Outliers.** Candidates, more than 3 median absolute deviations from "
                   "the median of their class (log RMS; method: Leys et al. 2013): "
                   + (", ".join(sorted(set(candidatos))) if candidatos else "none") + ".",
                   "For each candidate, write here whether it is an error or a real rare case.", ""]
    Path(ruta_reporte).write_text("\n".join(lineas), encoding="utf-8")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--simulado", action="store_true", help="usar data/simulado/")
    args = p.parse_args()
    cfg = cargar_config()
    if args.simulado:
        ruta_meta = carpeta(cfg, "simulated") / "metadata.csv"
        ruta_reporte = carpeta(cfg, "simulated") / "QUALITY-REPORT.md"
    else:
        ruta_meta, ruta_reporte = RAIZ / "data" / "metadata.csv", RAIZ / "QUALITY-REPORT.md"
    meta = leer_metadata(ruta_meta)
    if meta.empty:
        sys.exit(f"{ruta_meta} esta vacio: todavia no hay grabaciones.")
    nuevas, resumen = [], []
    for _, fila in meta.iterrows():
        ruta = (carpeta(cfg, "simulated") / fila["file_name"]) if args.simulado \
            else ruta_de_fila(cfg, fila)
        if not ruta.exists():                   # p. ej. prueba que solo vive en Azure
            print(f"  {fila['file_name']}: archivo no esta aqui, se conserva lo de metadata")
            nuevas.append(dict(fila))
            continue
        fila2, rms, cero_v = revisar_fila(fila, cfg, ruta)
        nuevas.append(fila2)
        if fila2["set"] == "train" and fila2["trials_rejected"] == "0":
            resumen.append({"file_name": fila2["file_name"], "session": fila2["session"],
                            "zero_level_v": cero_v,
                            "rest_rms_mv": 1000 * rms["rest"][0],
                            "move_rms_mv": 1000 * rms["move"][0]})
    meta2 = pd.DataFrame(nuevas)
    escribir_metadata(meta2, ruta_meta)
    escribir_reporte(meta2, pd.DataFrame(resumen), ruta_reporte)
    carpetas = [carpeta(cfg, "simulated")] if args.simulado else \
        [carpeta(cfg, "train"), carpeta(cfg, "test")]
    huerfanos = sorted(p.name for c in carpetas if c.exists() for p in c.glob("P*_S*_R*.csv")
                       if p.name not in set(meta2["file_name"]))
    if huerfanos:
        with open(ruta_reporte, "a", encoding="utf-8") as f:
            f.write("\n**Files without a metadata row** (the recorder was stopped before the "
                    "operator answered; they are not used): " + ", ".join(huerfanos) + ".\n")
        print(f"AVISO: archivos sin fila en metadata: {', '.join(huerfanos)}")
    rech = int((meta2["trials_rejected"].astype(str) == "1").sum())
    print(f"{len(meta2)} grabaciones, {rech} rechazadas. Reporte: {ruta_reporte.relative_to(RAIZ)}")


if __name__ == "__main__":
    main()
